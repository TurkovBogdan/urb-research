// Registry of the icons a research group may show: kebab name -> tabler component.
//
// The names are the contract with the backend (`research/icons.py::GROUP_ICONS`, served by the
// `group_icons` MCP tool); this file is the other half — the only place that turns such a name
// into something renderable. The imports are explicit on purpose: `@tabler/icons-vue` ships
// ~6000 components, so a runtime lookup over the whole package would pull all of them into the
// bundle and kill tree-shaking.
//
// A name outside the registry is not an error — the backend does not validate the stored value,
// so `groupIcon()` falls back to a folder rather than rendering nothing.

