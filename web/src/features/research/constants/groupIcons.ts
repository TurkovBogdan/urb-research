/** Icon component for a stored group icon name; unknown or empty -> the fallback. */
export function groupIcon(name: string | null | undefined): TablerIcon {
  if (!name) return GROUP_ICON_FALLBACK
  return GROUP_ICONS[name] ?? GROUP_ICON_FALLBACK
}

/** Every name the picker may offer, in the order the backend lists them. */
export function groupIconNames(): string[] {
  return Object.keys(GROUP_ICONS)
}
