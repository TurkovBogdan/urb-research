"""Палитра цветов группы — фиксированный набор имён.

Цвет группы не может быть произвольной строкой: тон должен читаться и в светлой, и в тёмной теме,
поэтому каждое имя — это не hex, а запись в реестре, где для него подобраны и промерены ступени
(``web/src/features/research/constants/groupColors.ts``). Этот список — канонический источник
набора; фронт держит зеркальную мапу «имя → ступени», парность половинок сторожит тест.

Имена — обиходные названия тонов в нижнем регистре, порядок по кругу (красный → розовый), в конце
нейтральный ``slate``: пикер показывает палитру как есть, и переход между соседними плитками
должен быть плавным.

Значение колонки ``research_group.color`` в БД **не** валидируется по этому набору — ровно как
``icon`` (см. ``icons.py``): жёсткая проверка превратила бы расширение палитры в правку двух
файлов на двух языках. Незнакомое имя фронт рисует акцентом приложения.
"""

from __future__ import annotations

GROUP_COLORS: tuple[str, ...] = (
    "red",
    "orange",
    "yellow",
    "green",
    "teal",
    "sky",
    "blue",
    "violet",
    "rose",
    "slate",
)


def group_colors() -> list[str]:
    """Палитра цветов группы в порядке показа."""
    return list(GROUP_COLORS)


__all__ = ["GROUP_COLORS", "group_colors"]
